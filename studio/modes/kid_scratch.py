"""
Mode 2: Kid GUI "Scratch" (Offline Blockly Visual Programming).

Pairs an offline Google Blockly workspace (`QWebEngineView` + `QWebChannel`) with the native
embedded OpenGL 3D simulator, real-time block highlighting, `.pycub_blocks` save/load, live
Python code preview, and one-click export to Mode 3 ("Kid Programming").
"""
from __future__ import annotations

import json
import os
from typing import Dict, Optional

from PySide6.QtCore import QObject, Qt, QTimer, QUrl, Signal, Slot
from PySide6.QtGui import QColor
from PySide6.QtWidgets import (
    QComboBox,
    QFileDialog,
    QFrame,
    QHBoxLayout,
    QLabel,
    QPlainTextEdit,
    QPushButton,
    QSplitter,
    QVBoxLayout,
    QWidget,
)

from icub_pybullet.runtime_paths import ensure_user_workspace
from studio.i18n import I18nManager
from studio.resource_paths import locate_studio_asset
from studio.theme import get_active_theme, get_theme_tokens
from studio.sim_bridge import SimProcessSupervisor, discover_all_worlds
from studio.widgets.code_editor import PythonCodeEditor
from studio.widgets.confetti import ConfettiOverlay
from studio.widgets.flow_layout import FlowLayout
from studio.widgets.viewport import EmbeddedGLViewer

try:
    from PySide6.QtWebChannel import QWebChannel
    from PySide6.QtWebEngineWidgets import QWebEngineView
    HAS_WEBENGINE = True
except Exception:  # pragma: no cover
    QWebChannel = None
    QWebEngineView = None
    HAS_WEBENGINE = False


class _BlocklyBridge(QObject):
    """Qt WebChannel bridge relaying Blockly workspace events to Python."""

    codeChanged = Signal(str)
    ready = Signal()

    @Slot(str)
    def onCodeChanged(self, code: str) -> None:
        """Emit updated clean Python code generated by the Blockly workspace."""
        self.codeChanged.emit(code)

    @Slot()
    def onReady(self) -> None:
        """Emit readiness signal once the Blockly page finishes initializing."""
        self.ready.emit()


class KidScratchMode(QWidget):
    """Mode 2 widget: Scratch-style visual block programming + native 3D simulator."""

    openInKidCodeRequested = Signal(str)

    def __init__(
        self,
        supervisor: SimProcessSupervisor,
        i18n: I18nManager,
        parent: Optional[QWidget] = None,
    ):
        """Initialize the Scratch Blockly mode UI, WebChannel bridge, and signals."""
        super().__init__(parent)
        self.sup = supervisor
        self.i18n = i18n
        self._active = False
        self._last_hits = 0
        self._clean_python = "from icub_pybullet.kid_api import *\n\nwave('right')\n"
        self._custom_world_path: Optional[str] = None
        self._web_ready = False
        self._web_loaded = False
        asset_html = locate_studio_asset("blockly", "index.html")
        self._html_path = (
            str(asset_html)
            if asset_html is not None
            else os.path.join(
                os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                "assets",
                "blockly",
                "index.html",
            )
        )

        self._build_ui()
        self.apply_theme(get_active_theme())
        self._connect_signals()
        self.retranslate_ui()

    def _build_ui(self) -> None:
        """Construct the Blockly workspace, Python preview, 3D viewer, and console layout."""
        root = QHBoxLayout(self)
        root.setContentsMargins(10, 10, 10, 10)

        splitter = QSplitter(Qt.Orientation.Horizontal, self)
        root.addWidget(splitter)

        # ================= LEFT PANEL: BLOCKLY WORKSPACE + TOOLBAR + PYTHON PREVIEW =================
        left_panel = QWidget()
        left_lay = QVBoxLayout(left_panel)
        left_lay.setContentsMargins(0, 0, 4, 0)
        left_lay.setSpacing(8)

        toolbar = FlowLayout(h_spacing=6, v_spacing=6)

        self.run_btn = QPushButton()
        self.run_btn.setStyleSheet(
            "background: #16a34a; color: white; font-weight: 800; padding: 8px 14px; border-radius: 9px;"
        )
        self.run_btn.clicked.connect(self._run_blocks)
        toolbar.addWidget(self.run_btn)

        self.stop_btn = QPushButton()
        self.stop_btn.setStyleSheet(
            "background: #dc2626; color: white; font-weight: 800; padding: 8px 14px; border-radius: 9px;"
        )
        self.stop_btn.clicked.connect(self._stop_blocks)
        toolbar.addWidget(self.stop_btn)

        self.save_btn = QPushButton()
        self.save_btn.clicked.connect(self._save_blocks)
        toolbar.addWidget(self.save_btn)

        self.load_btn = QPushButton()
        self.load_btn.clicked.connect(self._load_blocks)
        toolbar.addWidget(self.load_btn)

        self.clear_btn = QPushButton()
        self.clear_btn.clicked.connect(self._clear_blocks)
        toolbar.addWidget(self.clear_btn)

        self.preview_toggle_btn = QPushButton()
        self.preview_toggle_btn.setCheckable(True)
        self.preview_toggle_btn.toggled.connect(lambda on: self.preview_editor.setVisible(on))
        toolbar.addWidget(self.preview_toggle_btn)

        toolbar.addStretch(1)

        self.to_python_btn = QPushButton()
        self.to_python_btn.setStyleSheet(
            "background: #7c3aed; color: white; font-weight: 700; padding: 8px 12px; border-radius: 9px;"
        )
        self.to_python_btn.clicked.connect(self._export_to_kid_python)
        toolbar.addWidget(self.to_python_btn)
        left_lay.addLayout(toolbar)

        left_vsplit = QSplitter(Qt.Orientation.Vertical)
        if HAS_WEBENGINE:
            self.web_view = QWebEngineView(left_vsplit)
            self.web_view.page().setBackgroundColor(QColor("#f8fafc"))
            self._bridge = _BlocklyBridge(self)
            self._bridge.codeChanged.connect(self._on_clean_code_updated)
            self._bridge.ready.connect(self._on_blockly_ready)
            self._channel = QWebChannel(self.web_view.page())
            self._channel.registerObject("pyBridge", self._bridge)
            self.web_view.page().setWebChannel(self._channel)
            self.web_view.loadFinished.connect(self._on_web_load_finished)
            left_vsplit.addWidget(self.web_view)
        else:
            self.web_view = None
            fallback = QLabel("QtWebEngineWidgets is unavailable in this environment.")
            fallback.setAlignment(Qt.AlignmentFlag.AlignCenter)
            left_vsplit.addWidget(fallback)

        self.preview_editor = PythonCodeEditor()
        self.preview_editor.setReadOnly(True)
        self.preview_editor.setMaximumHeight(190)
        self.preview_editor.setVisible(False)
        left_vsplit.addWidget(self.preview_editor)
        left_vsplit.setSizes([560, 150])
        left_lay.addWidget(left_vsplit, 1)

        splitter.addWidget(left_panel)

        # ================= RIGHT PANEL: EMBEDDED 3D VIEWER + WORLD + OUTPUT =================
        right_panel = QWidget()
        right_lay = QVBoxLayout(right_panel)
        right_lay.setContentsMargins(4, 0, 0, 0)
        right_lay.setSpacing(8)

        top_bar = FlowLayout(h_spacing=6, v_spacing=6)
        self.status_lbl = QLabel()
        top_bar.addWidget(self.status_lbl)

        self.world_combo = QComboBox()
        self.world_combo.setMinimumWidth(100)
        self.world_combo.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
        self.world_combo.setMinimumContentsLength(10)
        self.world_combo.activated.connect(self._on_world_selected)
        top_bar.addWidget(self.world_combo)

        self.custom_world_btn = QPushButton("📄 .yaml")
        self.custom_world_btn.clicked.connect(self._browse_custom_world)
        top_bar.addWidget(self.custom_world_btn)

        self.restart_btn = QPushButton()
        self.restart_btn.clicked.connect(self._restart_world)
        top_bar.addWidget(self.restart_btn)

        self.reset_view_btn = QPushButton()
        self.reset_view_btn.clicked.connect(lambda: self.viewer.reset_view())
        top_bar.addWidget(self.reset_view_btn)
        right_lay.addLayout(top_bar)

        self.ball_lbl = QLabel()
        self.ball_lbl.setWordWrap(True)
        right_lay.addWidget(self.ball_lbl)

        self.viewer_frame = QFrame()
        vf_lay = QVBoxLayout(self.viewer_frame)
        vf_lay.setContentsMargins(2, 2, 2, 2)
        self.viewer = EmbeddedGLViewer(self.viewer_frame)
        vf_lay.addWidget(self.viewer, 1)
        self.confetti = ConfettiOverlay(self.viewer_frame)
        right_lay.addWidget(self.viewer_frame, 1)

        self.console = QPlainTextEdit()
        self.console.setReadOnly(True)
        self.console.setMaximumHeight(110)
        right_lay.addWidget(self.console)

        splitter.addWidget(right_panel)
        splitter.setSizes([660, 500])

    def apply_theme(self, theme: str) -> None:
        """Apply ``theme`` colors to status banners, viewer frame, and console."""
        t = get_theme_tokens(theme)
        self.status_lbl.setStyleSheet(f"font-weight: 700; color: {t.heading_accent};")
        self.ball_lbl.setStyleSheet(
            f"background: {t.banner_warn_bg}; border: 1px solid {t.banner_warn_border}; border-radius: 8px; "
            f"padding: 5px 10px; font-weight: 700; color: {t.banner_warn_fg};"
        )
        self.viewer_frame.setStyleSheet(
            f"border: 2px solid {t.viewer_border}; border-radius: 12px; background: {t.surface_alt_bg};"
        )
        self.console.setStyleSheet(
            f"background: {t.console_bg}; color: {t.console_fg}; font-family: monospace; font-size: 12px; "
            f"border: 1px solid {t.console_border}; border-radius: 8px;"
        )

    def _connect_signals(self) -> None:
        """Connect localization and simulator supervisor signals to mode slots."""
        self.i18n.languageChanged.connect(self._on_lang_changed)
        self.sup.sceneInitialized.connect(self._on_scene_init)
        self.sup.frameReady.connect(self._on_frame)
        self.sup.statusChanged.connect(self._on_status)
        self.sup.ballUpdated.connect(self._on_ball)
        self.sup.consoleOutput.connect(self._on_console)
        self.sup.blockHighlighted.connect(self._on_block_highlight)
        self.sup.kidScriptStateChanged.connect(self._on_kid_script_state)

    def activate_mode(self) -> None:
        """Activate the mode, load Blockly if needed, and start the interactive simulator."""
        self._active = True
        self._ensure_web_loaded()
        self._populate_worlds()
        self.viewer.set_overlay_status(self.i18n.t("status_loading"))
        self.sup.set_enabled_eyes(set())
        self.sup.start_interactive(self._selected_world())

    def showEvent(self, event) -> None:
        """Refresh the Blockly workspace layout shortly after the widget becomes visible."""
        super().showEvent(event)
        if self.web_view is not None and self._web_ready:
            QTimer.singleShot(50, self._refresh_blockly_view)

    def _ensure_web_loaded(self) -> None:
        """Load the local Blockly HTML page once or trigger a workspace resize."""
        if self.web_view is None:
            return
        if not self._web_loaded:
            self._web_loaded = True
            self.web_view.load(QUrl.fromLocalFile(os.path.realpath(self._html_path)))
        elif self._web_ready:
            QTimer.singleShot(50, self._refresh_blockly_view)

    def _refresh_blockly_view(self) -> None:
        """Trigger a Blockly workspace resize and repaint the web view."""
        if self.web_view is not None and self._web_ready:
            self.web_view.page().runJavaScript("if (window.pycubApi) window.pycubApi.resizeWorkspace();")
            self.web_view.update()

    def _on_web_load_finished(self, ok: bool) -> None:
        """Log an error to the console if the Blockly HTML page failed to load."""
        if not ok and self.web_view is not None:
            self.console.appendPlainText("Failed to load Scratch Blockly workspace.\n")

    def deactivate_mode(self) -> None:
        """Stop any running Blockly script and mark the mode inactive."""
        if self._active:
            self.sup.stop_kid_code()
        self._active = False

    def _on_blockly_ready(self) -> None:
        """Sync the active UI language to Blockly and refresh its layout."""
        self._web_ready = True
        if self.web_view is not None:
            self.web_view.page().runJavaScript(f"window.pycubApi.setLanguage({json.dumps(self.i18n.lang)});")
            QTimer.singleShot(50, self._refresh_blockly_view)

    def _on_lang_changed(self, lang: str) -> None:
        """Retranslate Qt widgets and update the Blockly workspace language."""
        self.retranslate_ui()
        if self.web_view is not None and self._web_ready:
            self.web_view.page().runJavaScript(f"window.pycubApi.setLanguage({json.dumps(lang)});")

    def _on_clean_code_updated(self, code: str) -> None:
        """Cache clean generated Python code and update the preview editor."""
        self._clean_python = code
        self.preview_editor.setPlainText(code)

    def _run_blocks(self) -> None:
        """Clear console output and execute instrumented Python generated from blocks."""
        self.console.clear()
        if self.web_view is None or not self._web_ready:
            self.sup.run_kid_code(self._clean_python, "<scratch_blocks>")
            return

        def _launch(instrumented_code: str) -> None:
            """Send instrumented or fallback clean code to the simulator runner."""
            code_to_run = str(instrumented_code) if instrumented_code else self._clean_python
            self.sup.run_kid_code(code_to_run, "<scratch_blocks>")

        self.web_view.page().runJavaScript("window.pycubApi.getInstrumentedPython();", _launch)

    def _stop_blocks(self) -> None:
        """Stop the active simulator script and clear any highlighted block."""
        self.sup.send_command({"cmd": "stop"})
        self._on_block_highlight(None)

    def _save_blocks(self) -> None:
        """Prompt for a file path and save the Blockly workspace JSON."""
        if self.web_view is None or not self._web_ready:
            return
        proj_dir = str(ensure_user_workspace() / "projects")
        path, _ = QFileDialog.getSaveFileName(
            self,
            self.i18n.t("save_blocks"),
            os.path.join(proj_dir, "my_blocks.pycub_blocks"),
            "pyCub Scratch Blocks (*.pycub_blocks *.json)",
        )
        if not path:
            return

        def _write(json_str: str) -> None:
            """Write serialized Blockly workspace JSON to the selected file."""
            if json_str:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(json_str)

        self.web_view.page().runJavaScript("window.pycubApi.saveWorkspaceJson();", _write)

    def _load_blocks(self) -> None:
        """Prompt for a saved blocks file and restore it into the Blockly workspace."""
        if self.web_view is None or not self._web_ready:
            return
        proj_dir = str(ensure_user_workspace() / "projects")
        path, _ = QFileDialog.getOpenFileName(
            self,
            self.i18n.t("load_blocks"),
            proj_dir,
            "pyCub Scratch Blocks (*.pycub_blocks *.json)",
        )
        if not path or not os.path.isfile(path):
            return
        with open(path, "r", encoding="utf-8") as f:
            raw = f.read()
        self.web_view.page().runJavaScript(f"window.pycubApi.loadWorkspaceJson({json.dumps(raw)});")

    def _clear_blocks(self) -> None:
        """Clear all blocks from the Blockly workspace."""
        if self.web_view is not None and self._web_ready:
            self.web_view.page().runJavaScript("window.pycubApi.clearWorkspace();")

    def _export_to_kid_python(self) -> None:
        """Emit clean generated Python code to open in Kid Programming mode."""
        if self.web_view is None or not self._web_ready:
            self.openInKidCodeRequested.emit(self._clean_python)
            return

        def _emit(clean: str) -> None:
            """Emit the clean Python code via ``openInKidCodeRequested``."""
            self.openInKidCodeRequested.emit(clean or self._clean_python)

        self.web_view.page().runJavaScript("window.pycubApi.getCleanPython();", _emit)

    def _populate_worlds(self) -> None:
        """Refresh the world selector combo box with built-in and custom worlds."""
        prev = self.world_combo.currentData()
        self.world_combo.blockSignals(True)
        self.world_combo.clear()
        li = self.i18n.lang_idx
        for wid, (labels, _cfg) in discover_all_worlds().items():
            self.world_combo.addItem(labels[li], wid)
        if self._custom_world_path and os.path.isfile(self._custom_world_path):
            self.world_combo.addItem(f"📄 {os.path.basename(self._custom_world_path)}", self._custom_world_path)
        idx = self.world_combo.findData(prev or self.sup.current_world or "ball")
        self.world_combo.setCurrentIndex(max(0, idx))
        self.world_combo.blockSignals(False)

    def _selected_world(self) -> str:
        """Return the currently selected world identifier or custom YAML path."""
        return str(self.world_combo.currentData() or "ball")

    def _on_world_selected(self, _idx: int) -> None:
        """Restart the interactive simulator using the newly selected world."""
        self._last_hits = 0
        self.viewer.set_overlay_status(self.i18n.t("status_loading"))
        self.sup.start_interactive(self._selected_world())

    def _browse_custom_world(self) -> None:
        """Prompt for a custom YAML world config and load it in the simulator."""
        ws_worlds = str(ensure_user_workspace() / "worlds")
        path, _ = QFileDialog.getOpenFileName(self, "Select World YAML", ws_worlds, "YAML (*.yaml *.yml)")
        if path and os.path.isfile(path):
            self._custom_world_path = os.path.abspath(path)
            self._populate_worlds()
            self.world_combo.setCurrentIndex(self.world_combo.findData(self._custom_world_path))
            self._on_world_selected(0)

    def _restart_world(self) -> None:
        """Reload the currently selected world in the interactive simulator."""
        self._last_hits = 0
        self.viewer.set_overlay_status(self.i18n.t("status_loading"))
        self.sup.start_interactive(self._selected_world())

    # --- Worker Signals ---

    def _on_scene_init(self, manifest: Dict) -> None:
        """Load scene meshes into the 3D viewer and toggle the ball banner."""
        if not self._active:
            return
        self.viewer.load_scene_manifest(manifest)
        self.viewer.set_overlay_status("")
        has_ball = any("ball" in os.path.basename(m.get("path", "")).lower() for m in manifest.get("meshes", []))
        self.ball_lbl.setVisible(has_ball)

    def _on_frame(self, frame: Dict) -> None:
        """Update the 3D viewer with a newly rendered simulator frame."""
        if self._active:
            self.viewer.update_frame(frame)

    def _on_status(self, st: Dict) -> None:
        """Update status label, viewer overlay, and console from worker status updates."""
        if not self._active:
            return
        state = st.get("state", "ready")
        if state == "loading":
            txt = f"{self.i18n.t('status_loading')} {st.get('detail', '')}".strip()
            self.status_lbl.setText(txt)
            self.viewer.set_overlay_status(txt)
        elif state == "error":
            detail = str(st.get("detail", "")).strip()
            self.status_lbl.setText("❌ Error loading world")
            self.viewer.set_overlay_status("Error loading world")
            if detail:
                self.console.appendPlainText(detail + "\n")
        else:
            self.status_lbl.setText(self.i18n.t("status_ready"))
            self.viewer.set_overlay_status("")

    def _on_kid_script_state(self, ev: Dict) -> None:
        """Update the status label when a block script starts or finishes."""
        if not self._active:
            return
        if ev.get("running"):
            self.status_lbl.setText(self.i18n.t("status_running_code"))
        else:
            self.status_lbl.setText(self.i18n.t("status_ready"))

    def _on_block_highlight(self, block_id: object) -> None:
        """Highlight the currently executing Blockly block or clear highlighting."""
        if self._active and self.web_view is not None and self._web_ready:
            js_arg = json.dumps(str(block_id)) if block_id else "null"
            self.web_view.page().runJavaScript(f"window.pycubApi.highlightBlock({js_arg});")

    def _on_ball(self, ball: Dict) -> None:
        """Update ball telemetry text and trigger confetti when hit count increases."""
        if not self._active or not ball:
            return
        hits = int(ball.get("hits", 0))
        if hits > self._last_hits:
            self._last_hits = hits
            self.confetti.burst()
        if not ball.get("touched"):
            self.ball_lbl.setText(self.i18n.t("ball_waiting"))
        else:
            d = ball.get("distance")
            a = ball.get("after")
            self.ball_lbl.setText(
                self.i18n.t(
                    "ball_stats",
                    hits=hits,
                    dist=f"{d:.1f}" if isinstance(d, (int, float)) else "—",
                    after=f"{a:.1f}" if isinstance(a, (int, float)) else "…",
                )
            )

    def _on_console(self, _stream: str, text: str) -> None:
        """Append stdout/stderr text from the simulator worker to the console."""
        if self._active and text:
            self.console.moveCursor(self.console.textCursor().MoveOperation.End)
            self.console.insertPlainText(text)

    def retranslate_ui(self) -> None:
        """Update all widget labels and world options for the active language."""
        self.run_btn.setText(self.i18n.t("run_program"))
        self.stop_btn.setText(self.i18n.t("stop_program"))
        self.save_btn.setText(self.i18n.t("save_blocks"))
        self.load_btn.setText(self.i18n.t("load_blocks"))
        self.clear_btn.setText(self.i18n.t("clear_blocks"))
        self.preview_toggle_btn.setText(self.i18n.t("show_python_preview"))
        self.to_python_btn.setText(self.i18n.t("to_kid_python"))
        self.restart_btn.setText(self.i18n.t("restart_world"))
        self.reset_view_btn.setText(self.i18n.t("reset_view"))
        self.status_lbl.setText(self.i18n.t("status_ready"))
        self.ball_lbl.setText(self.i18n.t("ball_waiting"))
        self._populate_worlds()
